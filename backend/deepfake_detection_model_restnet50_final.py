def predict_video(video_path, num_frames=20):

    cap = cv2.VideoCapture(video_path)

    # Get total number of frames
    total_frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))

    if total_frames <= 0:
        cap.release()
        raise ValueError("Could not read this video.")

    # Select frames throughout the video
    frame_indices = np.linspace(
        0,
        total_frames - 1,
        min(num_frames, total_frames),
        dtype=int
    )

    fake_probs = []

    # Process each selected frame
    for frame_index in frame_indices:

        cap.set(cv2.CAP_PROP_POS_FRAMES,int(frame_index))

        success, frame = cap.read()

        if not success:
            continue

        # Convert BGR to RGB
        frame = cv2.cvtColor(frame,cv2.COLOR_BGR2RGB)


        # Convert frame to PIL image
        image = Image.fromarray(frame)

        # Apply preprocessing
        image_tensor = transform(image).unsqueeze(0).to(device)


        # Make prediction
        with torch.no_grad():
            outputs = model(image_tensor)
            probabilities = torch.softmax(outputs,dim=1)


        # Get FAKE class probability
        fake_index = class_to_idx["FAKE"]

        fake_probability = probabilities[0,fake_index].item()

        fake_probs.append(fake_probability)

    cap.release()


    if len(fake_probs) == 0:
        raise ValueError("No readable frames were found.")

    # Calculate average probabilities
    avg_fake = float(np.mean(fake_probs))
    avg_real = 1.0 - avg_fake


    # Display results
    print("VIDEO ANALYSIS RESULTS")
    print("----------------------------")
    print("Frames analyzed:",len(fake_probs))
    print(f"Average FAKE score: {avg_fake:.2%}")
    print(f"Average REAL score: {avg_real:.2%}")

    # Final prediction
    if avg_fake >= 0.5:
        print("\nPrediction: FAKE")
    else:
        print("\nPrediction: REAL")

    return avg_fake

